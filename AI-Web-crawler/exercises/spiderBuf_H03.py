myheaders = {
    'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.164 Safari/537.36'}


def getHTML(url, file_name=''):
    resp = requests.get(url, headers=myheaders, timeout=10)
    resp.raise_for_status()
    # 响应头未必带 charset，按页面实际编码解码，避免中文乱码
    resp.encoding = resp.apparent_encoding or 'utf-8'
    html = resp.text

    if file_name != '':
        with open(file_name, 'w', encoding='utf-8') as f:
            f.write(html)

    return html


def downloadImage(url, path=''):
    if url == '':
        return

    file_name = Path(path) / url.split('/').pop()
    if file_name.exists():   # 海报可能在多页里重复出现，不重复下载
        return

    img_data = requests.get(url, headers=myheaders, timeout=10).content
    with open(file_name, 'wb') as img:
        img.write(img_data)


def getNextToken(html):
    """取出隐藏 div 里的下一页 token，最后一页没有则返回空串"""
    root = etree.HTML(html)
    tokens = root.xpath('//div[@id="%s"]/text()' % NEXT_TOKEN_ID)
    return tokens[0].strip() if len(tokens) > 0 else ''


def parseDetail(detail):
    """
    详情区里的字段只有两种形状：
        <span>豆瓣电影评分:</span> 9.1<br/>
        <span><span>类型:</span><span>剧情 </span></span>/剧情 / 奇幻 / 冒险<br/>
    标签取内层第一个 span（没有内层就取自身），值优先取外层 span 后面的 tail
    （那里是完整列表），tail 为空时退回内层第二个 span。
    """
    fields = {}

    for span in detail.xpath('./span'):
        inner = span.xpath('./span')

        label = (inner[0].text if len(inner) > 0 else span.text) or ''
        label = label.strip().rstrip(':：')

        value = (span.tail or '').strip().lstrip('/').strip()
        if value == '' and len(inner) > 1:
            value = (inner[1].text or '').strip()

        if label != '':
            fields[label] = value

    return fields


def parseHTML(html):
    """解析一页里的所有电影，顺带把海报下载到 data/h03 下，返回电影列表"""
    root = etree.HTML(html)

    # 信息行和简介行成对出现，靠有没有 h2 区分，不靠下标奇偶
    rows = root.xpath('//div[@class="row" and contains(@style, "margin-top: 10px;")]')

    movies = []
    i = 0
    while i < len(rows):
        row = rows[i]
        h2s = row.xpath('.//h2')
        if len(h2s) == 0:
            i += 1
            continue

        movie = {'title': (h2s[0].text or '').strip()}

        # 海报
        img_urls = row.xpath('.//img/@src')
        movie['poster_url'] = urljoin(base_url, img_urls[0]) if len(img_urls) > 0 else ''
        downloadImage(movie['poster_url'], str(outdir))

        # 评分、导演、编剧……
        details = row.xpath('.//div[contains(@class, "col-lg-9")]')
        fields = parseDetail(details[0]) if len(details) > 0 else {}
        for key, label in FIELD_LABELS:
            movie[key] = fields.get(label, '')

        # 简介在紧跟着的下一行
        movie['summary'] = ''
        if i + 1 < len(rows) and len(rows[i + 1].xpath('.//h2')) == 0:
            summary = rows[i + 1].xpath('string()').strip()
            for prefix in ('简介：', '简介:'):
                if summary.startswith(prefix):
                    summary = summary[len(prefix):].strip()
                    break
            movie['summary'] = summary
            i += 1   # 简介行已经用掉了

        movies.append(movie)

        print(movie['title'])
        print(movie['poster_url'])
        for key, _ in FIELD_LABELS:
            print(movie[key])
        print(movie['summary'])
        print('-' * 40)

        i += 1

    return movies


